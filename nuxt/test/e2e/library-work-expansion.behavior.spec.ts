for (const mode of ["works", "latest"]) {
  test(`${mode} duplicate titlepaths restore only the chosen main author's disclosure`, async ({ page }) => {
    const base = `/bibliotek?visa=${mode}&filter=duplicate-titles&keep=first&keep=second&fras=kyrka%20%26%20slott`
    const rows = page.locator(mode === "latest" ? "[data-library-latest-row]" : "[data-library-work-row]")
    const toggles = rows.locator("[data-library-work-toggle]")
    await page.goto(`${base}&title=SamladeSkrifter`, { waitUntil: "networkidle" })
    await expect(toggles).toHaveCount(2)
    await expect(toggles.nth(0)).toHaveAttribute("aria-expanded", "false")
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "false")
    await toggles.nth(1).click()
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "true")
    await expect.poll(() => new URL(page.url()).searchParams.get("title_author")).toBe("StrindbergA")
    expect(new URL(page.url()).searchParams.getAll("keep")).toEqual(["first", "second"])
    expect(new URL(page.url()).searchParams.get("fras")).toBe("kyrka & slott")
    const ssr = await page.request.get(page.url())
    const html = await ssr.text()
    expect(await page.evaluate(markup => Array.from(new DOMParser().parseFromString(markup, "text/html").querySelectorAll("[data-library-work-toggle]")).map(element => element.getAttribute("aria-expanded")), html)).toEqual(["false", "true"])
    await page.reload({ waitUntil: "networkidle" })
    await expect(toggles.nth(0)).toHaveAttribute("aria-expanded", "false")
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "true")
    await toggles.nth(0).press("Enter")
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "false")
    await expect.poll(() => new URL(page.url()).searchParams.get("title_author")).toBe("SöderbergH")
    await page.goBack()
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "true")
    await expect(toggles.nth(0)).toHaveAttribute("aria-expanded", "false")
    await toggles.nth(1).press("Space")
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "false")
    await expect.poll(() => new URL(page.url()).searchParams.has("title")).toBe(false)
    await expect.poll(() => new URL(page.url()).searchParams.has("title_author")).toBe(false)
    await page.goto(`${base}&title=SamladeSkrifter&title_author=UnknownAuthor`, { waitUntil: "networkidle" })
    await expect(toggles.nth(0)).toHaveAttribute("aria-expanded", "false")
    await expect(toggles.nth(1)).toHaveAttribute("aria-expanded", "false")
  })
}
