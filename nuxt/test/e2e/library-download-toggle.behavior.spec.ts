import { expect, test } from "@playwright/test"

for (const width of [390, 1440]) {
  test(`download-mode button is keyboard reachable and toggles once at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto("/bibliotek?avancerat&keep=ja", { waitUntil: "networkidle" })
    await page.locator('[data-library-mounted="true"]').waitFor({ state: "attached" })
    const toggle = page.locator("[data-library-download-mode]")
    expect(await toggle.evaluate(element => element.tagName)).toBe("BUTTON")
    await expect(toggle).toHaveAttribute("type", "button")
    await expect(toggle).toHaveAttribute("aria-pressed", "false")
    await expect(toggle).toHaveCSS("cursor", "pointer")
    await expect(toggle).toHaveCSS("border-top-style", "solid")
    await expect(toggle).toHaveCSS("border-top-width", "1px")
    await page.getByRole("combobox", { name: "Språk …", exact: true }).focus()
    await page.keyboard.press("Tab")
    await expect(toggle).toBeFocused()
    await expect(toggle).toHaveCSS("outline-style", "solid")
    await toggle.screenshot({ path: testInfo.outputPath("download-mode-toggle.png") })
    await page.keyboard.press("Enter")
    await expect(toggle).toHaveAttribute("aria-pressed", "true")
    await expect(toggle).toHaveText(/Stäng källmaterial/)
    await expect.poll(() => new URL(page.url()).searchParams.get("nedladdning")).toBe("1")
    await expect(page.locator("[data-library-format-button]")).toBeVisible()
    await expect(toggle).toBeFocused()
    await page.keyboard.press("Space")
    await expect(toggle).toHaveAttribute("aria-pressed", "false")
    await expect(toggle).toHaveText(/Ladda ner källmaterial/)
    await expect.poll(() => new URL(page.url()).searchParams.has("nedladdning")).toBe(false)
    expect(new URL(page.url()).searchParams.get("keep")).toBe("ja")
    await expect(page.locator("[data-library-format-button]")).toHaveCount(0)
    const box = await toggle.boundingBox()
    expect(box).not.toBeNull()
    expect(box!.x + box!.width).toBeLessThanOrEqual(width)
  })
}
